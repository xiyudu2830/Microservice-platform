#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."

: "${KUBE_CONTEXT:?Set KUBE_CONTEXT to the demo cluster context}"
namespace=${KUBE_NAMESPACE:-governance}
kube=(kubectl --context "$KUBE_CONTEXT" --namespace "$namespace")
bash scripts/init-demo.sh

pg_password=$(sed -n 's/^POSTGRES_PASSWORD=//p' .env)
mongo_password=$(sed -n 's/^MONGO_PASSWORD=//p' .env)
[[ $pg_password =~ ^[0-9a-f]+$ && $mongo_password =~ ^[0-9a-f]+$ ]] ||
  { echo "Use the hex database passwords generated by init-demo.sh" >&2; exit 1; }

"${kube[@]}" create namespace "$namespace" --dry-run=client -o yaml |
  "${kube[@]}" apply --server-side -f -
{
  sed -nE '/^(INTERNAL_RPC_KEY|BOOTSTRAP_EMAIL|BOOTSTRAP_PASSWORD|POSTGRES_PASSWORD|MONGO_PASSWORD)=/p' .env
  printf 'POSTGRES_DSN=postgres://governance:%s@governance-postgres:5432/governance?sslmode=disable\n' "$pg_password"
  printf 'MONGO_URI=mongodb://governance:%s@governance-mongo:27017/?authSource=admin\n' "$mongo_password"
} | "${kube[@]}" create secret generic governance-secrets --from-env-file=/dev/stdin --dry-run=client -o yaml |
  "${kube[@]}" apply --server-side -f -

helm upgrade --install governance deploy/helm/governance \
  --kube-context "$KUBE_CONTEXT" --namespace "$namespace" \
  --set demo.enabled=true --set image.pullPolicy=Never \
  --set-string image.tag="${IMAGE_TAG:-local}" --atomic --wait --timeout 5m
